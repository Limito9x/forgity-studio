import { keepPreviousData } from "@tanstack/react-query";
import { createMutationHook } from "@/lib/query-utils";
import * as RunnersApi from "@/gen/endpoints/runners/runners";
import type {
  RunnerDto,
  RunnerHardwareProfile,
  RunnerGpuInfo,
  RunnerDiskInfo,
  ExecutorCandidateDto,
  RunnerExecutorConfigDto,
  SetupTokenDto,
  AttachRunnerToStudioRequest,
} from "../types";
import type { DiscoverRunnerFoldersParams } from "@/gen/model";

export type {
  RunnerDto,
  RunnerHardwareProfile,
  RunnerGpuInfo,
  RunnerDiskInfo,
  ExecutorCandidateDto,
  RunnerExecutorConfigDto,
  SetupTokenDto,
  AttachRunnerToStudioRequest,
};

export const useRunners = () => {
  return RunnersApi.useGetRunners<RunnerDto[]>(undefined, {
    query: {
      placeholderData: keepPreviousData,
      staleTime: 60_000,
      select: (data: any) => data as unknown as RunnerDto[],
    },
  });
};

export const useStudioRunners = (studioId?: string) => {
  return RunnersApi.useGetStudioRunners<RunnerDto[]>(
    studioId || "",
    {
      query: {
        enabled: !!studioId,
        placeholderData: keepPreviousData,
      staleTime: 60_000,
        select: (data: any) => {
          const list = Array.isArray(data) ? data : data?.items || [];
          return list
            .filter((item: any) => item && (item.runner || item.runnerId))
            .map((item: any) => {
              const r = item.runner || {};
              return {
                ...r,
                id: item.runnerId || r.id,
                name: item.alias || r.name || "Runner",
                machineKey: r.machineKey || "",
                executorConfigs: r.executorConfigs || [],
              } as RunnerDto;
            });
        },
      },
    }
  );
};

export const useDiscoverRunnerFolder = (
  id: string,
  pathOrParams?: string | DiscoverRunnerFoldersParams
) => {
  const params: DiscoverRunnerFoldersParams | undefined =
    typeof pathOrParams === "string"
      ? { path: pathOrParams }
      : pathOrParams;

  return RunnersApi.useDiscoverRunnerFolders(
    id,
    params,
    {
      query: {
        enabled: !!id,
        placeholderData: keepPreviousData,
      staleTime: 60_000,
      },
    }
  );
};

